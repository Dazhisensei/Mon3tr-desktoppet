/**
 * 时段定义（按本地小时）。
 *
 * 边界取整数小时，便于理解和调整：
 *   早晨 5–9 / 上午 9–11 / 午间 11–14 / 下午 14–17
 *   傍晚 17–19 / 晚间 19–23 / 深夜 23–5
 */
export const SLOTS = {
  dawn:  { from: 5,  to: 9,  label: '早晨' },
  morn:  { from: 9,  to: 11, label: '上午' },
  noon:  { from: 11, to: 14, label: '午间' },
  aft:   { from: 14, to: 17, label: '下午' },
  eve:   { from: 17, to: 19, label: '傍晚' },
  night: { from: 19, to: 23, label: '晚间' },
  late:  { from: 23, to: 5,  label: '深夜' },
};

/**
 * 判断某个小时属于哪个时段。
 * @param {number} hour 0–23
 * @returns {string} 时段 key
 */
export function slotOfHour(hour) {
  const h = ((Number(hour) % 24) + 24) % 24;
  for (const [key, s] of Object.entries(SLOTS)) {
    // 深夜跨零点，单独处理
    if (key === 'late') continue;
    if (h >= s.from && h < s.to) return key;
  }
  return 'late';
}

/** 便捷版：按 Date 判断时段。 */
export function slotOf(date = new Date()) {
  return slotOfHour(date.getHours());
}

