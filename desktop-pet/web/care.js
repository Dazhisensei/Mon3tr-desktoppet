/**
 * 抽取可用于当前时段的语句。
 *
 * 通用语句（无 slots）任何时候都可用；带标签的只在匹配时段可用。
 *
 * @param {string} slot
 * @returns {Array<{text:string, slots?:string[]}>}
 */
export function candidatesFor(slot) {
  return CARE_LINES.filter((c) => !c.slots || c.slots.includes(slot));
}

/**
 * 选一句关心的话。
 *
 * **不追求纯随机**：当前时段的专属语句会拿到更高权重，
 * 让「早餐」提醒更可能出现在早上。但通用语句仍有机会出现，
 * 否则同一时段反复只有那两条会很单调。
 *
 * @param {{slot?: string, random?: () => number, exclude?: string[]}} opts
 *        exclude 用于避免连续重复
 * @returns {string} 语句文本
 */
export function pickCareLine(opts = {}) {
  const rnd = opts.random || Math.random;
  const slot = opts.slot || slotOf();
  const exclude = new Set(opts.exclude || []);

  let pool = candidatesFor(slot).filter((c) => !exclude.has(c.text));
  // 全被排除时（语句少、连抽多次）放开排除限制，保证一定有话可说
  if (!pool.length) pool = candidatesFor(slot);
  if (!pool.length) pool = CARE_LINES;

  // 时段专属语句权重更高：通用 : 专属 = 1 : 3
  const weighted = [];
  for (const c of pool) {
    const w = c.slots ? 3 : 1;
    for (let i = 0; i < w; i++) weighted.push(c);
  }

  const idx = Math.floor(rnd() * weighted.length) % weighted.length;
  return weighted[idx].text;
}

/** 测试与调试用：当前时段有多少条专属语句。 */
export function slotLineCount(slot) {
  return CARE_LINES.filter((c) => c.slots && c.slots.includes(slot)).length;
}

